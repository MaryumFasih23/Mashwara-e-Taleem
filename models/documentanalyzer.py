def grammar_check(text: str, max_issues: int = 25) -> dict:
    matches = lt_tool.check(text)
    corrected = language_tool_python.utils.correct(text, matches)

    issues = []
    for m in matches[:max_issues]:
        issues.append({
            "message": m.message,
            "context": m.context,
            "replacements": m.replacements[:5]
        })

    # FIX 2: Compute a 0-100 grammar quality score (higher = fewer issues, better quality)
    # Penalise ~2 points per issue, floor at 0
    issue_count = len(matches)
    grammar_quality_score = max(0, 100 - issue_count * 2)

    return {
        "count": issue_count,                        # raw issue count (e.g. 22)
        "grammar_quality_score": grammar_quality_score,  # 0-100 quality score (e.g. 56)
        "issues": issues,
        "corrected": corrected
    }


