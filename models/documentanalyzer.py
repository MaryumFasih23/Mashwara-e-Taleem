def ask_llm_json(prompt: str, max_tokens: int = 2500, temperature: float = 0.0) -> dict:
    if "client" not in globals():
        raise RuntimeError("Groq client not found. Define `client = Groq(...)` in a separate cell first.")
    if "LLM_MODEL" not in globals():
        raise RuntimeError("LLM_MODEL not found. Define `LLM_MODEL = ...` in your Groq cell first.")

    r = client.chat.completions.create(
        model=LLM_MODEL,
        messages=[{"role": "user", "content": prompt}],
        temperature=temperature,
        max_tokens=max_tokens
    )
    return safe_json_parse(r.choices[0].message.content)


# =========================
# READ DOCUMENT
# =========================
def read_pdf(path: str) -> str:
    reader = PdfReader(path)
    return "\n".join([(p.extract_text() or "") for p in reader.pages]).strip()

def read_docx(path: str) -> str:
    d = docx.Document(path)
    return "\n".join([p.text for p in d.paragraphs]).strip()

def read_txt(path: str) -> str:
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        return f.read().strip()

def read_document(path: str) -> str:
    ext = os.path.splitext(path)[1].lower()
    if ext == ".pdf":
        return read_pdf(path)
    if ext == ".docx":
        return read_docx(path)
    if ext == ".txt":
        return read_txt(path)
    raise ValueError("Unsupported file type (.pdf/.docx/.txt)")


