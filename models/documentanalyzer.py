def load_data(university_csv: str, program_csv: str):
    unis = pd.read_csv(university_csv)
    progs = pd.read_csv(program_csv)

    unis["combined"] = unis.fillna("").astype(str).agg(" | ".join, axis=1)
    progs["combined"] = progs.fillna("").astype(str).agg(" | ".join, axis=1)

    return unis, progs

def build_index(df: pd.DataFrame, text_col: str, pkl_path: str):
    texts = df[text_col].fillna("").astype(str).tolist()

    if os.path.exists(pkl_path):
        with open(pkl_path, "rb") as f:
            emb = pickle.load(f)
        emb = np.array(emb, dtype="float32")
    else:
        emb = embedder.encode(texts, normalize_embeddings=True)
        emb = np.array(emb, dtype="float32")
        with open(pkl_path, "wb") as f:
            pickle.dump(emb, f)

    index = faiss.IndexFlatIP(emb.shape[1])
    index.add(emb)
    return index

def retrieve(df: pd.DataFrame, index, query: str, k: int = 3) -> pd.DataFrame:
    q = embedder.encode([query], normalize_embeddings=True).astype("float32")
    D, I = index.search(q, k)
    out = df.iloc[I[0]].copy()
    out["score"] = D[0]
    return out


