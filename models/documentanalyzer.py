def analyze(doc, uni, prog, uni_csv, prog_csv):
    text = read_document(doc)

    grammar = grammar_check(text)
    classification = classify(text)
    doc_type = classification.get("doc_type", "SOP")

    fmt = format_check(text, doc_type)

    unis, progs = load_data(uni_csv, prog_csv)
    uni_index = build_index(unis, "combined", UNI_EMB_PKL)
    prog_index = build_index(progs, "combined", PROG_EMB_PKL)

    context = build_context(unis, progs, uni_index, prog_index, uni, prog)

    prog_fit = program_fit_score(text, context)

