# =========================
# FORMAT CHECK
# FIX 3: Only evaluate sections relevant to the detected doc_type
# =========================
def format_check(text: str, doc_type: str) -> dict:
    lower = text.lower()
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    first_para = lines[0] if lines else ""

    checks = {}

    if doc_type == "RESUME":
        # Only check resume sections for a RESUME doc
        checks["resume_header"]     = bool(re.search(r"\bemail\b|@\w+|\bphone\b|\bmobile\b|\blinkedin\b|\bgithub\b", text, re.I))
        checks["resume_education"]  = bool(re.search(r"\beducation\b|\bdegree\b|\buniversity\b|\bcgpa\b|\bgpa\b", text, re.I))
        checks["resume_experience"] = bool(re.search(r"\bexperience\b|\bemployment\b|\bwork history\b", text, re.I))
        checks["resume_projects"]   = bool(re.search(r"\bprojects?\b|\bportfolio\b", text, re.I))
        checks["resume_skills"]     = bool(re.search(r"\bskills?\b|\btechnologies\b|\btools\b", text, re.I))
        checks["resume_extras"]     = bool(re.search(r"\bcertifications?\b|\bawards?\b|\bvolunteer\b|\bleadership\b", text, re.I))

        required = ["resume_header", "resume_education", "resume_experience", "resume_skills"]

    else:
        # Only check SOP sections for an SOP doc
        # broad intro: any meaningful opening (passionate, motivated, or paragraph > 50 chars)
        checks["sop_intro"] = (
            "statement of purpose" in lower
            or "i am applying" in lower
            or "i wish to pursue" in lower
            or "i am excited" in lower
            or "i am interested" in lower
            or bool(re.search(r"\b(passionate|motivated|aspiring|enthusiastic|as a)\b", lower))
            or len(first_para) > 50
        )
        checks["sop_academics"]      = bool(re.search(r"\b(bachelor|undergraduate|degree|cgpa|gpa|university|graduation|college)\b", lower))
        checks["sop_experience"]     = bool(re.search(r"\b(intern|internship|project|research|work experience|worked|employment)\b", lower))
        checks["sop_why_program"]    = bool(re.search(r"\b(program|curriculum|courses|specialization|research interests|master)\b", lower))
        checks["sop_why_university"] = bool(re.search(r"\b(university|faculty|lab|research group|department|campus|institution)\b", lower))
        # broader goals: future tense, intentions, career mentions
        checks["sop_goals"] = bool(re.search(
            r"\b(career goals?|short[- ]term|long[- ]term|i aim to|i plan to|aspire|i hope to|i intend|my goal|after (completing|graduation)|future)\b",
            lower
        ))
        checks["sop_conclusion"] = bool(re.search(
            r"\b(in conclusion|thank you|i look forward|i would be honored|i am confident|i believe|i hope to|i am eager)\b",
            lower
        ))

        required = ["sop_intro", "sop_academics", "sop_experience", "sop_goals"]

    missing = [r for r in required if not checks.get(r)]

    # Also flag optional-but-important missing sections
    if doc_type == "RESUME" and not checks.get("resume_projects"):
        missing.append("resume_projects")
    if doc_type == "SOP" and not checks.get("sop_conclusion"):
        missing.append("sop_conclusion")

    return {
        "is_correct_format": (len(missing) == 0),
        "missing_sections": missing,
        "section_checks": checks
    }


