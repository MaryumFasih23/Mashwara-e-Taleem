def save_output(result: dict, out_path: str = "improved_document.txt"):
    lines = []

    ev = result.get("evaluation", {})
    doc_type = result.get("classification", {}).get("doc_type", "DOCUMENT")

    lines.append("=" * 60)
    lines.append(f"  DOCUMENT ANALYSIS REPORT — {doc_type}")
    lines.append("=" * 60)

    # Scores summary
    lines.append("\n📊 SCORES SUMMARY")
    lines.append("-" * 40)
    lines.append(f"  Overall Score      : {ev.get('overall_score', 'N/A')} / 100")
    lines.append(f"  Quality Label      : {ev.get('overall_quality_label', 'N/A')}")

    grammar = ev.get("grammar", {})
    lines.append(f"  Grammar Score      : {grammar.get('score', 'N/A')} / 100  ({result['grammar']['count']} issues found)")

    prog_spec = ev.get("program_specificity", {})
    prog_fit_val = result["program_fit"]["program_fit_score"]
    fit_suffix = "  ⚠️  Document appears unrelated to target program." if prog_fit_val == 0 else ""
    lines.append(f"  Program Fit Score  : {prog_fit_val} / 100{fit_suffix}")

    if result.get("ats_score"):
        lines.append(f"  ATS Score          : {result['ats_score']['ats_score']} / 100")

    clarity = ev.get("clarity", {})
    lines.append(f"  Clarity Score      : {clarity.get('score', 'N/A')} / 100")

    relevance = ev.get("relevance_to_selected_program", {})
    lines.append(f"  Program Relevance  : {relevance.get('score', 'N/A')} / 100")

    # Format
    lines.append("\n📋 FORMAT CHECK")
    lines.append("-" * 40)
    fmt = ev.get("format_and_sections", {})
    lines.append(f"  Correct Format     : {fmt.get('is_correct_format', 'N/A')}")
    missing = fmt.get("missing_sections", [])
    lines.append(f"  Missing Sections   : {missing if missing else 'None'}")

    # Strengths / Weaknesses
    lines.append("\n✅ STRENGTHS")
    lines.append("-" * 40)
    for s in ev.get("strengths", []) or ["None identified"]:
        lines.append(f"  • {s}")

    lines.append("\n❌ WEAKNESSES")
    lines.append("-" * 40)
    for w in ev.get("weaknesses", []) or ["None identified"]:
        lines.append(f"  • {w}")

    # Grammar issues
    lines.append("\n🔤 TOP GRAMMAR ISSUES")
    lines.append("-" * 40)
    for issue in grammar.get("top_issues", [])[:5]:
        lines.append(f"  • {issue}")

    # Keywords
    lines.append("\n🔑 MISSING PROGRAM KEYWORDS")
    lines.append("-" * 40)
    missing_kws = prog_spec.get("missing_keywords_to_add", [])
    lines.append(f"  {', '.join(missing_kws) if missing_kws else 'None'}")
    lines.append(f"  Add in: {', '.join(prog_spec.get('where_to_add_keywords', []))}")

    # ATS suggestions
    if result.get("ats_score"):
        lines.append("\n🤖 ATS SUGGESTIONS")
        lines.append("-" * 40)
        for sug in result["ats_score"].get("suggestions", []):
            lines.append(f"  • {sug}")

    # Sentence improvements
    lines.append("\n✏️  SENTENCE-LEVEL IMPROVEMENTS")
    lines.append("-" * 40)
    for imp in (ev.get("sentence_level_improvements") or [])[:5]:
        if imp.get("original"):
            lines.append(f"  BEFORE : {imp['original']}")
            lines.append(f"  AFTER  : {imp['improved']}")
            lines.append(f"  WHY    : {imp['why']}")
            lines.append("")

    # Action plan
    lines.append("\n📌 ACTION PLAN FOR NEXT REVISION")
    lines.append("-" * 40)
    for step in (ev.get("action_plan_next_revision") or []):
        lines.append(f"  • {step}")

    # Rewritten document
    lines.append("\n" + "=" * 60)
    lines.append("  REWRITTEN DOCUMENT")
    lines.append("=" * 60 + "\n")

    improved = ""
    ro = ev.get("rewrite_output", {})
    if isinstance(ro, dict):
        improved = ro.get("improved_document", "") or ""

    if isinstance(improved, str):
        s = improved.strip()
        try:
            parsed = json.loads(s)
            if isinstance(parsed, dict):
                parts = []
                for k, v in parsed.items():
                    parts.append(k.upper())
                    parts.append("-" * len(k))
                    parts.append("")
                    parts.append(str(v))
                    parts.append("\n")
                improved = "\n".join(parts).strip()
        except:
            pass

    lines.append(improved.strip() if improved.strip() else "No rewrite generated.")

    full_output = "\n".join(lines)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(full_output)

    print(f"✅ Saved report to: {out_path}")
    # NOTE: intentionally no return value — returning the string caused notebooks
    # to print the raw repr (with escaped \n) as the cell's last expression output.


