# PROGRAM KEYWORDS (FROM CONTEXT)
# FIX 4: Strip URLs and noise tokens before ranking keywords
# =========================
def extract_program_keywords(context: str, top_k: int = 30) -> list:
    # Remove full URLs first so fragments like "adance" from "advancedcomputinginstitute" don't slip through
    context_clean = re.sub(r"https?://\S+", " ", context)
    context_clean = re.sub(r"www\.\S+", " ", context_clean)

    # Extract only alphabetic tokens of length >= 4 (avoids "www", "http", 3-letter noise)
    words = re.findall(r"[a-zA-Z]{4,}", context_clean.lower())

    # Filter against expanded stoplist
    words = [w for w in words if w not in KEYWORD_STOPLIST and not w.isdigit()]

    freq = {}
    for w in words:
        freq[w] = freq.get(w, 0) + 1

    sorted_words = sorted(freq.items(), key=lambda x: x[1], reverse=True)
    return [w for w, _ in sorted_words[:top_k]]


def program_fit_score(text: str, context: str) -> dict:
    tl = text.lower()
    kws = extract_program_keywords(context, top_k=30)

    hits = [k for k in kws if k in tl]
    missing = [k for k in kws if k not in tl]

    score = min(100, int(len(hits) * (100 / max(1, len(kws)))))

    return {
        "program_fit_score": score,
        "matched_keywords": hits[:25],
        "missing_keywords": missing[:25],
        "keywords_used": kws
    }


